fn identity() -> Value {
    let compiled_sources = COMPILED_INPUTS
        .iter()
        .map(|(n, b)| (*n, digest::hash(b)))
        .collect::<BTreeMap<_, _>>();
    json!({"kind":"fixed-literal32-reference-r1","manifest_dir":env!("CARGO_MANIFEST_DIR"),"engine_revision":shell::EVALUATOR_REVISION,"fixture_sha256":FIXED_SHA,"host_cases":32,"GNU_exclusion_reasons":8,"compiled_sources":compiled_sources})
}
fn main() {
    let args = std::env::args().skip(1).collect::<Vec<_>>();
    assert!(args.is_empty() || args == ["--identity"]);
    assert_eq!(shell::EVALUATOR_REVISION, 15);
    assert_eq!(digest::hash(FIXED), FIXED_SHA);
    let fixture: Value = serde_json::from_slice(FIXED).unwrap();
    assert!(fixture["host_execution"].is_null() && fixture["source_identity"].is_null());
    let rows = fixture["cases"].as_array().unwrap();
    assert_eq!(rows.len(), 32);
    assert_eq!(fixture["vm_only"].as_array().unwrap().len(), 8);
    if !args.is_empty() {
        println!("{}", identity());
        return;
    }
    let mut actual = vec![];
    for row in rows {
        assert!(row["observed"].is_null());
        let files = row["files"]
            .as_object()
            .unwrap()
            .iter()
            .map(|(n, t)| {
                assert!(!n.contains('/') && n != "." && n != "..");
                (format!("/work/{n}"), t.as_str().unwrap().to_owned())
            })
            .collect();
        let case = shell::Case {
            name: row["id"].as_str().unwrap().into(),
            args: row["args"]
                .as_array()
                .unwrap()
                .iter()
                .map(|a| a.as_str().unwrap().to_owned())
                .collect(),
            stdin: row["stdin"].as_str().unwrap().into(),
            env: BTreeMap::new(),
            files,
            stdout: String::new(),
            stderr: String::new(),
            status: 0,
            after: BTreeMap::new(),
        };
        let mut vm = shell::Vm::new(row["vm_source"].as_str().unwrap(), &case).unwrap();
        for _ in 0..100_000 {
            if vm.done() {
                break;
            }
            vm.tick(7);
        }
        assert!(vm.done());
        actual.push(json!({"id":row["id"],"row_sha256":digest::hash(serde_json::to_string(row).unwrap().as_bytes()),"outcome":vm.outcome}));
    }
    println!(
        "{}",
        json!({"identity":identity(),"outcomes":actual,"GNU_exclusions":fixture["vm_only"]})
    );
}
